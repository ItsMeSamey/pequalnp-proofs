"""Discover a column-generated interface, contract it, and join exact F3 signs."""
from itertools import combinations, product


def subtract(a,b,scale):
    return tuple((x-scale*y)%3 for x,y in zip(a,b))


def remainder(v, basis):
    for p,row in sorted(basis.items()):
        if v[p]:
            v=subtract(v,row,v[p])
    return v


def plan(vectors, transfer, mode):
    n=len(vectors)
    shared={}
    for j in (transfer if mode=="contract" else ()):
        v=remainder(vectors[j],shared)
        p=next((i for i,a in enumerate(v) if a),None)
        if p is not None:
            shared[p]=tuple(v[p]*a%3 for a in v)
    # Track each quotient dependent column's coordinates on original basis columns.
    basis={}
    coords={}
    parents=list(range(n))
    def root(i):
        while parents[i]!=i:
            parents[i]=parents[parents[i]]
            i=parents[i]
        return i
    gone=set(transfer) if mode=="pin" else set()
    for j,column in enumerate(vectors):
        if j in gone:
            continue
        v=remainder(column,shared)
        expr=[0]*n
        for p,(row,cache) in sorted(basis.items()):
            if v[p]:
                k=v[p]
                v=subtract(v,row,k)
                expr=[(a+k*b)%3 for a,b in zip(expr,cache)]
        p=next((i for i,a in enumerate(v) if a),None)
        if p is None:
            coords[j]={i:a for i,a in enumerate(expr) if a}
            for i in coords[j]:
                parents[root(j)]=root(i)
        else:
            expr=[(-x)%3 for x in expr]
            expr[j]=1
            basis[p]=(tuple(v[p]*a%3 for a in v),tuple(v[p]*a%3 for a in expr))
    blocks={}
    for j in range(n):
        if j in gone:
            continue
        blocks.setdefault(root(j),[]).append(j)
    nullities=[sum(j in coords for j in block) for block in blocks.values()]
    peak=max(3**len(shared),1<<max(nullities,default=0))
    if mode=="pin":
        peak=1<<(len(transfer)+max(nullities,default=0))
    return peak,len(shared),list(blocks.values()),coords,basis


def full_support(cols, *, search_rank=1, supplied=None, cap=None, modes=("contract","pin")):
    """Return (status, dict of column signs or None, diagnostics).

    A supplied interface is a list of column IDs; otherwise all independent
    candidate spans generated by at most search_rank columns are covered.
    cap bounds a local sign enumeration or transfer-table cardinality.
    """
    if type(search_rank) is not int or search_rank<0 or cap is not None and (type(cap) is not int or cap<0):
        raise ValueError("invalid transfer budget")
    ids=sorted(cols)
    vectors=[tuple(cols[i]) for i in ids]
    h=len(vectors[0]) if vectors else 0
    if any(len(v)!=h or any(type(x) is not int or x not in (0,1,2) for x in v) for v in vectors):
        raise ValueError("invalid ternary columns")
    if supplied is None:
        candidates=(s for k in range(min(search_rank,len(ids))+1) for s in combinations(range(len(ids)),k))
    else:
        supplied=tuple(supplied)
        if len(set(supplied))!=len(supplied) or not set(supplied)<=set(ids):
            raise ValueError("invalid transfer set")
        candidates=[tuple(ids.index(i) for i in supplied)]
    modes=tuple(modes)
    if not modes or not set(modes)<={"contract","pin"}:
        raise ValueError("invalid transfer conditioning mode")
    best=None
    tried=0
    for candidate in candidates:
        for mode in modes:
            tried+=1
            result=plan(vectors,candidate,mode)
            if best is None or result[0]<best[0]:
                best=result
                used,method=candidate,mode
    peak,t,blocks,coords,basis=best
    stats=dict(transfer_ids=tuple(ids[j] for j in used),transfer_rank=t,transfer_blocks=len(blocks),
               transfer_bound=peak,transfer_plans=tried,transfer_peak=1,transfer_mode=method)
    # A quotient coloop forbids a full-support dependency, even before capped enumeration.
    if method=="contract" and any(all(j not in coords for j in block) for block in blocks):
        return "UNSAT",None,stats
    if cap is not None and peak>cap:
        return "UNKNOWN",None,stats
    if method=="pin":
        for chosen in product((1,2),repeat=len(used)):
            value=tuple(-sum(vectors[j][k]*s for j,s in zip(used,chosen))%3 for k in range(h))
            desired=[0]*len(ids)
            for p,(row,cache) in sorted(basis.items()):
                if value[p]:
                    a=value[p]
                    value=subtract(value,row,a)
                    desired=[(x+a*y)%3 for x,y in zip(desired,cache)]
            if any(value):
                continue
            solution=dict(zip(used,chosen))
            for block in blocks:
                dep=[j for j in block if j in coords]
                ind=[i for i in block if i not in coords]
                for signs in product((1,2),repeat=len(dep)):
                    local=dict(zip(dep,signs))
                    local.update((i,(desired[i]-sum(coords[j].get(i,0)*local[j] for j in dep))%3) for i in ind)
                    if all(local.values()):
                        solution.update(local)
                        break
                else:
                    break
            else:
                answer={ids[j]:s for j,s in solution.items()}
                assert all(sum(answer[i]*cols[i][k] for i in ids)%3==0 for k in range(h))
                return "SAT",answer,stats
        return "UNSAT",None,stats
    zero=(0,)*h
    states={zero:0}
    for block in blocks:
        dep=[j for j in block if j in coords]
        ind=[i for i in block if i not in coords]
        gains={}
        for signs in product((1,2),repeat=len(dep)):
            values=dict(zip(dep,signs))
            values.update((i,-sum(coords[j].get(i,0)*values[j] for j in dep)%3) for i in ind)
            if all(values.values()):
                gain=tuple(sum(s*vectors[j][k] for j,s in values.items())%3 for k in range(h))
                witness=sum(1<<j for j,s in values.items() if s==2)
                gains.setdefault(gain,witness)
        if not gains:
            return "UNSAT",None,stats
        nxt={}
        for prev,trace in states.items():
            for gain,witness in gains.items():
                nxt.setdefault(tuple((x+y)%3 for x,y in zip(prev,gain)),trace|witness)
        states=nxt
        stats['transfer_peak']=max(stats['transfer_peak'],len(states))
    if zero not in states:
        return "UNSAT",None,stats
    word=states[zero]
    answer={i:1+((word>>j)&1) for j,i in enumerate(ids)}
    assert all(sum(answer[i]*cols[i][k] for i in ids)%3==0 for k in range(h))
    return "SAT",answer,stats
