"""Scheduler 04 source: matching-hull quotient, original NAND counts and lifts."""
from itertools import product
from unittest.mock import patch
import incident_total
from check_branch_nand_04 import physical_source, replay
from check_mux_single_block_04 import physical_chart
from check_total_nand_04 import truth_count


def accepted(bits, rows):
    return all(any(bits[u] ^ bits[v] == d for u, v, d in row) for row in rows)


def audit(rows, n, seeded, expected_sat, method="hull"):
    _, pins = physical_chart(rows)
    source = physical_source(len(rows), pins, suffix=3)
    count = sum(accepted(bits, rows) for bits in product((0, 1), repeat=n))
    assert bool(count) == expected_sat
    assert truth_count(source) == 2 * count
    with patch.object(incident_total, "biclique_dual_witness",
                      wraps=incident_total.biclique_dual_witness) as dual:
        raw = incident_total.incident_block_witness(len(rows), pins, method=method)
        assert dual.called == seeded
    assert (raw is not None) == expected_sat
    if raw is not None:
        for g, a, b, c in product((0, 1), repeat=4):
            assert bool(replay(source, (*raw, g, a, b, c))) == (
                a != b and b == g and c == raw[0])


def main():
    # Port chords are edges 2,3, while the comparison DFS uses chords 1,3.
    # The guarantee is generated by mask 1 in port coordinates and mask 3
    # in solver coordinates. The target is this nonzero guaranteed vector.
    rows = [((1, 0, 1), (2, 1, 0)), ((0, 2, 0), (2, 1, 0))]
    edges = tuple(e for pair in rows for e in pair)
    with patch.object(incident_total, "biclique_dual_witness",
                      wraps=incident_total.biclique_dual_witness) as dual:
        values = incident_total.incident_comparison_witness(3, edges, method="hull")
        assert values is not None and accepted(values, rows)
        projected_columns, projected_target, _ = dual.call_args.args
        assert projected_target == 0 and projected_columns == [0, 1, 0, 1]
    audit(rows, 3, True, True)
    audit(rows + [((2, 2, 1), (2, 2, 1))], 3, True, False)
    audit([((0, 1, 0), (2, 3, 1))], 4, False, True)
    audit([((0, 0, 1), (1, 1, 1))], 2, False, False)
    # Opposite paired square edges give a full guarantee and an odd target.
    square = [((0, 1, 1), (2, 3, 0)), ((1, 2, 0), (3, 0, 0))]
    audit(square, 4, False, True)
    audit(square, 4, True, True, method="blockwise")
    assert incident_total.incident_block_witness(1, [(0, 0, 1)]) is None
    print("Transported hull direction, 5 distinct physical NAND truth tables, blockwise and fallback replay")


if __name__ == "__main__":
    main()
